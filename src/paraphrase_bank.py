# --------------------------------------------------------------------------- 物差しとの類似度チェック
def _norm(s: str) -> str:
    s = unicodedata.normalize("NFKC", s).lower()
    s = re.sub(r"\d+", "0", s)  # 数字は区別しない（算数の文型比較のため）
    return "".join(ch for ch in s if ch not in "、。，,．・（）()「」『』“”\"'！!？?：:；;~〜 \u3000\t\n")


def _bigrams(s: str) -> set[str]:
    return {s[i:i + 2] for i in range(len(s) - 1)} or {s}


def similarity(a: str, b: str) -> float:
    """文字2-gramのJaccard類似度（0〜1）。"""
    ba, bb = _bigrams(_norm(a)), _bigrams(_norm(b))
    return len(ba & bb) / len(ba | bb)


def all_bank_phrases() -> list[tuple[str, str]]:
    """(種類, 文面) の一覧。算数は代表的な数字を入れた文面にする。"""
    out = [("言い換え", p) for ps in PARAPHRASES.values() for p in ps]
    for kind, forms in ARITH_PHRASINGS.items():
        out += [(f"算数/{kind}", f.format(123, 456)) for f in forms]
    return out


def check_against_yardstick(yardstick_path: str, threshold: float = 0.70) -> list[str]:
    with open(yardstick_path, encoding="utf-8") as f:
        yard = [json.loads(line)["input"] for line in f if line.strip()]
    problems = []
    for kind, phrase in all_bank_phrases():
        for y in yard:
            if _norm(phrase) == _norm(y):
                problems.append(f"[同一] {kind}: 「{phrase}」 = 物差し「{y}」")
            elif similarity(phrase, y) >= threshold:
                problems.append(f"[類似 {similarity(phrase, y):.2f}] {kind}: 「{phrase}」 ≈ 物差し「{y}」")
    return problems


def check_structure() -> list[str]:
    """キーが実在する質問か、各項目に十分な言い換えがあるかを確認する。"""
    from src.generate_data import CODE_SAMPLES, CONVERSATION_SAMPLES, QA_KNOWLEDGE_PAIRS, TECH_SAMPLES
    originals = {q for q, _e, _a in (*QA_KNOWLEDGE_PAIRS, *TECH_SAMPLES, *CODE_SAMPLES, *CONVERSATION_SAMPLES)}
    problems = [f"元の質問に存在しないキー: {k}" for k in PARAPHRASES if k not in originals]
    problems += [f"言い換えが未登録の質問: {q}" for q in sorted(originals) if q not in PARAPHRASES]
    problems += [f"言い換えが少ない({len(v)}件): {k}" for k, v in PARAPHRASES.items() if len(v) < 4]
    for k, v in PARAPHRASES.items():
        if len(set(v)) != len(v) or k in v:
            problems.append(f"重複あり: {k}")
    return problems


